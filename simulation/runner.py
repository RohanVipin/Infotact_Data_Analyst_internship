"""Unified simulation runner coordinating engine event generation with output sinks.

Coordinates SimulationEngine with the Stage 6.1 OutputSink architecture (JsonlSink,
KafkaSink, and CompositeOutputSink) into a unified, reliable execution pipeline for
AtmoSync sensor telemetry.

Architectural Guarantees:
1. Single Event Identity: Generated immutable SensorEvent instances are passed by reference
   to all active sinks without regeneration, re-serialization, or mutation.
2. Failure Policy: Supports FAIL_FAST (default) where sink dispatch or simulation exceptions
   immediately halt execution and propagate unmasked.
3. Accurate Metrics: Enforces a strict distinction between synchronous sink dispatch results
   and asynchronous Kafka broker delivery acknowledgements.
4. Predictable Lifecycle: Guaranteed flushing on normal completion or error, with resource
   cleanup adhering strictly to ownership contracts.
"""

from dataclasses import dataclass
from datetime import datetime, timezone
import logging
import time
from typing import Any, Callable, Dict, List, Optional, Tuple, Union

from simulation.events.event_schema import SensorEvent
from simulation.kafka.delivery_report import PublishingStats
from simulation.kafka.kafka_producer import SensorEventKafkaProducer
from simulation.output.sink import CompositeOutputSink, KafkaSink, OutputSink
from simulation.simulator.simulation_engine import SimulationEngine

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class RunnerMetrics:
    """Immutable snapshot of SimulationRunner execution metrics.

    Attributes:
        events_generated: Total sensor readings generated by the simulation engine.
        sink_dispatch_attempted: Total events submitted to the output sink.
        sink_dispatch_succeeded: Total events accepted by the output sink synchronously.
        sink_dispatch_failed: Total events that failed synchronous sink dispatch.
        simulation_cycles_completed: Fully completed simulation cycles.
        simulation_cycles_failed: Simulation cycles that encountered an error.
        kafka_delivery_acknowledged: Kafka messages confirmed delivered by broker (or None if no Kafka sink).
        kafka_delivery_failed: Kafka messages reported failed by broker (or None if no Kafka sink).
        kafka_pending: Kafka messages enqueued but awaiting broker ack (or None if no Kafka sink).
        status: Execution status ('INITIALIZED', 'RUNNING', 'COMPLETED', 'PARTIAL_FAILURE', 'FAILED', 'STOPPED').
        start_time: ISO-8601 UTC timestamp of execution start (or None).
        end_time: ISO-8601 UTC timestamp of execution end (or None).
        duration_seconds: Elapsed wall-clock execution time in seconds.
    """

    events_generated: int = 0
    sink_dispatch_attempted: int = 0
    sink_dispatch_succeeded: int = 0
    sink_dispatch_failed: int = 0
    simulation_cycles_completed: int = 0
    simulation_cycles_failed: int = 0
    kafka_delivery_acknowledged: Optional[int] = None
    kafka_delivery_failed: Optional[int] = None
    kafka_pending: Optional[int] = None
    status: str = "INITIALIZED"
    start_time: Optional[str] = None
    end_time: Optional[str] = None
    duration_seconds: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        """Return a dictionary representation of execution metrics."""
        return {
            "events_generated": self.events_generated,
            "sink_dispatch_attempted": self.sink_dispatch_attempted,
            "sink_dispatch_succeeded": self.sink_dispatch_succeeded,
            "sink_dispatch_failed": self.sink_dispatch_failed,
            "simulation_cycles_completed": self.simulation_cycles_completed,
            "simulation_cycles_failed": self.simulation_cycles_failed,
            "kafka_delivery_acknowledged": self.kafka_delivery_acknowledged,
            "kafka_delivery_failed": self.kafka_delivery_failed,
            "kafka_pending": self.kafka_pending,
            "status": self.status,
            "start_time": self.start_time,
            "end_time": self.end_time,
            "duration_seconds": round(self.duration_seconds, 4),
        }


# Type alias for external callers
SimulationResult = RunnerMetrics


class SimulationRunner:
    """Unified simulation pipeline runner coordinating event generation and output dispatch.

    Attributes:
        engine: The SimulationEngine generating canonical SensorEvent instances.
        output_sink: The OutputSink (or CompositeOutputSink) receiving events.
        fail_fast: If True, halts execution on the first simulation or dispatch failure.
        owns_sink: If True, the runner closes the output sink upon completion or shutdown.
            If False, only flushes the sink, leaving resource closure to the external caller.
    """

    def __init__(
        self,
        engine: SimulationEngine,
        output_sink: OutputSink,
        fail_fast: bool = True,
        owns_sink: bool = True,
        sleep_fn: Optional[Callable[[float], None]] = None,
    ) -> None:
        """Initialize the SimulationRunner.

        Args:
            engine: Validated SimulationEngine instance.
            output_sink: Validated OutputSink instance.
            fail_fast: Whether to immediately abort and propagate exceptions on error.
            owns_sink: Whether this runner owns and should close the sink on shutdown.
            sleep_fn: Optional callable for intervals between cycles (defaults to engine._sleep_fn).

        Raises:
            TypeError: If engine or output_sink are not instances of their expected base classes.
        """
        if not isinstance(engine, SimulationEngine):
            raise TypeError(
                f"engine must be an instance of SimulationEngine, got {type(engine).__name__}"
            )
        if not isinstance(output_sink, OutputSink):
            raise TypeError(
                f"output_sink must be an instance of OutputSink, got {type(output_sink).__name__}"
            )

        self._engine = engine
        self._output_sink = output_sink
        self._fail_fast = bool(fail_fast)
        self._owns_sink = bool(owns_sink)

        if sleep_fn is not None:
            self._sleep_fn = sleep_fn
        elif hasattr(engine, "_sleep_fn") and callable(getattr(engine, "_sleep_fn")):
            self._sleep_fn = getattr(engine, "_sleep_fn")
        else:
            self._sleep_fn = time.sleep

        # Internal operational metrics
        self._events_generated: int = 0
        self._sink_dispatch_attempted: int = 0
        self._sink_dispatch_succeeded: int = 0
        self._sink_dispatch_failed: int = 0
        self._simulation_cycles_completed: int = 0
        self._simulation_cycles_failed: int = 0

        # State tracking
        self._status: str = "INITIALIZED"
        self._start_time: Optional[datetime] = None
        self._end_time: Optional[datetime] = None
        self._stopped: bool = False
        self._is_closed: bool = False

    @property
    def engine(self) -> SimulationEngine:
        """Return the underlying SimulationEngine instance."""
        return self._engine

    @property
    def output_sink(self) -> OutputSink:
        """Return the configured OutputSink instance."""
        return self._output_sink

    @property
    def fail_fast(self) -> bool:
        """Return True if fail-fast error handling is enabled."""
        return self._fail_fast

    @property
    def owns_sink(self) -> bool:
        """Return True if the runner owns the output sink lifecycle."""
        return self._owns_sink

    @property
    def is_stopped(self) -> bool:
        """Return True if the runner or engine has been requested to stop."""
        return self._stopped or self._engine.is_stopped

    @property
    def is_closed(self) -> bool:
        """Return True if the runner has been shut down."""
        return self._is_closed

    @property
    def status(self) -> str:
        """Return the current execution status string."""
        return self._status

    def stop(self) -> None:
        """Gracefully request the runner and underlying engine to halt execution."""
        self._stopped = True
        self._engine.stop()
        if self._status == "RUNNING":
            self._status = "STOPPED"

    def _collect_kafka_metrics(self) -> Tuple[Optional[int], Optional[int], Optional[int]]:
        """Extract and aggregate broker delivery metrics across all active Kafka sinks.

        Returns:
            Tuple of (acknowledged, failed, pending), or (None, None, None) if no Kafka sink is present.
        """
        stats_objects: List[Any] = []

        # Case 1: Direct KafkaSink or object exposing producer.stats
        if hasattr(self._output_sink, "producer") and hasattr(
            getattr(self._output_sink, "producer"), "stats"
        ):
            stats_objects.append(getattr(self._output_sink, "producer").stats)
        elif hasattr(self._output_sink, "stats"):
            stats_objects.append(getattr(self._output_sink, "stats"))

        # Case 2: CompositeOutputSink inspecting child sinks
        elif isinstance(self._output_sink, CompositeOutputSink):
            for child_sink in self._output_sink.sinks:
                if hasattr(child_sink, "producer") and hasattr(
                    getattr(child_sink, "producer"), "stats"
                ):
                    stats_objects.append(getattr(child_sink, "producer").stats)
                elif hasattr(child_sink, "stats"):
                    stats_objects.append(getattr(child_sink, "stats"))

        if not stats_objects:
            return None, None, None

        acknowledged = 0
        failed = 0
        pending = 0
        for st in stats_objects:
            if isinstance(st, PublishingStats) or hasattr(st, "delivered"):
                d = getattr(st, "delivered", 0)
                f = getattr(st, "failed", 0)
                p = getattr(st, "pending", 0)
                if isinstance(d, int):
                    acknowledged += d
                if isinstance(f, int):
                    failed += f
                if isinstance(p, int):
                    pending += p

        return acknowledged, failed, pending

    def _compute_final_status(
        self,
        max_cycles: Optional[int],
        in_flight_exc: Optional[BaseException],
    ) -> str:
        """Evaluate the honest, comprehensive status of the completed simulation run.

        Accurately distinguishes between:
        - COMPLETED: All simulation cycles succeeded, all synchronous sink dispatches succeeded,
          and all asynchronous broker deliveries confirmed with zero failures.
        - PARTIAL_FAILURE: Simulation completed cycles, but one or more sink dispatches failed,
          or asynchronous broker delivery experienced failures or unacknowledged timeouts.
        - FAILED: Execution aborted due to unhandled exceptions, zero cycles/dispatches succeeded,
          or all required deliveries failed completely.
        - STOPPED: Execution was requested to halt gracefully before completing all cycles.
        """
        if in_flight_exc is not None:
            return "FAILED"

        cycles_executed = self._simulation_cycles_completed + self._simulation_cycles_failed
        ack, fail, pend = self._collect_kafka_metrics()

        has_cycle_failure = self._simulation_cycles_failed > 0
        has_dispatch_failure = self._sink_dispatch_failed > 0
        has_kafka_failure = (fail is not None and fail > 0) or (pend is not None and pend > 0)

        any_failure = has_cycle_failure or has_dispatch_failure or has_kafka_failure

        was_stopped_early = (self._stopped or self._engine.is_stopped) and (
            max_cycles is None or cycles_executed < max_cycles
        )

        if was_stopped_early:
            if any_failure:
                return "PARTIAL_FAILURE"
            return "STOPPED"

        if not any_failure:
            return "COMPLETED"

        # Determine complete failure (FAILED) vs partial failure (PARTIAL_FAILURE)
        is_kafka_only = isinstance(self._output_sink, KafkaSink) or (
            hasattr(self._output_sink, "producer") and not hasattr(self._output_sink, "sinks")
        )

        if self._simulation_cycles_completed == 0:
            return "FAILED"
        if self._sink_dispatch_succeeded == 0:
            return "FAILED"
        if is_kafka_only and (ack is not None and ack == 0 and (fail or 0) > 0):
            return "FAILED"

        return "PARTIAL_FAILURE"

    def get_metrics(self) -> RunnerMetrics:
        """Return an immutable snapshot of current execution metrics."""
        # Calculate wall-clock duration
        if self._start_time is not None:
            end = self._end_time if self._end_time is not None else datetime.now(timezone.utc)
            duration = max(0.0, (end - self._start_time).total_seconds())
        else:
            duration = 0.0

        ack, fail, pend = self._collect_kafka_metrics()

        return RunnerMetrics(
            events_generated=self._events_generated,
            sink_dispatch_attempted=self._sink_dispatch_attempted,
            sink_dispatch_succeeded=self._sink_dispatch_succeeded,
            sink_dispatch_failed=self._sink_dispatch_failed,
            simulation_cycles_completed=self._simulation_cycles_completed,
            simulation_cycles_failed=self._simulation_cycles_failed,
            kafka_delivery_acknowledged=ack,
            kafka_delivery_failed=fail,
            kafka_pending=pend,
            status=self._status,
            start_time=self._start_time.isoformat() if self._start_time else None,
            end_time=self._end_time.isoformat() if self._end_time else None,
            duration_seconds=duration,
        )

    def run_cycle(
        self,
        observed_at: Optional[Union[str, datetime]] = None,
    ) -> List[SensorEvent]:
        """Execute one complete simulation cycle and dispatch generated events.

        Args:
            observed_at: Optional fixed observation timestamp for the cycle.

        Returns:
            List of SensorEvent objects generated and dispatched during this cycle.

        Raises:
            RuntimeError: If the runner is closed.
            Exception: Propagates any engine simulation or sink dispatch exception under fail_fast.
        """
        if self._is_closed:
            raise RuntimeError("Cannot run cycle: SimulationRunner is closed")

        # 1. Generate events via the simulation engine
        try:
            cycle_events = self._engine.run_cycle(observed_at=observed_at)
        except Exception as exc:
            self._simulation_cycles_failed += 1
            self._status = "FAILED"
            logger.error("Simulation engine cycle failure: %s", exc)
            raise

        cycle_had_failure = False

        # 2. Dispatch events one-by-one to the output sink
        for event in cycle_events:
            self._events_generated += 1
            self._sink_dispatch_attempted += 1
            try:
                self._output_sink.write_event(event)
                self._sink_dispatch_succeeded += 1
            except Exception as exc:
                self._sink_dispatch_failed += 1
                cycle_had_failure = True
                self._status = "FAILED"
                logger.error(
                    "Output sink dispatch failure for event_id=%s: %s",
                    getattr(event, "event_id", "unknown"),
                    exc,
                )
                if self._fail_fast:
                    self._simulation_cycles_failed += 1
                    raise

        if cycle_had_failure:
            self._simulation_cycles_failed += 1
        else:
            self._simulation_cycles_completed += 1

        return cycle_events

    def run(self, max_cycles: Optional[int] = None) -> RunnerMetrics:
        """Run the simulation pipeline for a finite number of cycles or continuously.

        Args:
            max_cycles: Optional positive integer count of cycles to execute.
                If None, runs continuously until stop() is invoked.

        Returns:
            RunnerMetrics snapshot summarizing the completed execution.

        Raises:
            ValueError: If max_cycles is not a positive integer.
            RuntimeError: If the runner has already been closed.
            Exception: Propagates unhandled simulation, sink, or flush failures.
        """
        if max_cycles is not None:
            if not isinstance(max_cycles, int) or isinstance(max_cycles, bool) or max_cycles <= 0:
                raise ValueError(f"max_cycles must be a positive integer, got {max_cycles!r}")

        if self._is_closed:
            raise RuntimeError("Cannot run: SimulationRunner is closed")

        self._stopped = False
        self._start_time = datetime.now(timezone.utc)
        self._end_time = None
        self._status = "RUNNING"

        interval = self._engine.config.simulation.interval_seconds
        in_flight_exc: Optional[BaseException] = None

        try:
            while not self._stopped and not self._engine.is_stopped:
                cycles_executed = self._simulation_cycles_completed + self._simulation_cycles_failed
                if max_cycles is not None and cycles_executed >= max_cycles:
                    break

                self.run_cycle()

                cycles_executed = self._simulation_cycles_completed + self._simulation_cycles_failed
                # Sleep between cycles if another cycle remains
                if not self._stopped and not self._engine.is_stopped:
                    if max_cycles is None or cycles_executed < max_cycles:
                        self._sleep_fn(interval)

        except BaseException as exc:
            in_flight_exc = exc
            self._status = "FAILED"
            raise
        finally:
            self._end_time = datetime.now(timezone.utc)
            # 1. Execute guaranteed shutdown/flushing FIRST so all sinks drain delivery callbacks
            self._shutdown(in_flight_exc=in_flight_exc)

            # 2. Evaluate comprehensive final status AFTER shutdown completes flushing
            self._status = self._compute_final_status(max_cycles=max_cycles, in_flight_exc=in_flight_exc)

        return self.get_metrics()

    def run_continuously(self) -> RunnerMetrics:
        """Run the simulation continuously until stop() is called."""
        return self.run(max_cycles=None)

    def flush(self) -> None:
        """Flush buffered events to the configured output sink."""
        self._output_sink.flush()

    def close(self, in_flight_exc: Optional[BaseException] = None) -> None:
        """Flush buffers and release held resources."""
        self._shutdown(in_flight_exc=in_flight_exc)

    def _shutdown(self, in_flight_exc: Optional[BaseException] = None) -> None:
        """Internal helper coordinating sink flush and resource cleanup.

        Args:
            in_flight_exc: If present, suppresses cleanup exceptions so the original
                application exception is preserved.
        """
        if self._is_closed:
            return

        cleanup_errors: List[Exception] = []

        # 1. Flush configured sink
        try:
            self._output_sink.flush()
        except Exception as exc:
            logger.error("Error flushing output sink during runner shutdown: %s", exc)
            cleanup_errors.append(exc)

        # 2. Close sink resources if owned by this runner
        if self._owns_sink:
            try:
                self._output_sink.close()
            except Exception as exc:
                logger.error("Error closing output sink during runner shutdown: %s", exc)
                cleanup_errors.append(exc)

        self._is_closed = True

        # If an application exception is already in-flight, never mask it
        if in_flight_exc is not None:
            return

        # If normal shutdown encountered errors, mark FAILED and raise first error
        if cleanup_errors:
            self._status = "FAILED"
            raise cleanup_errors[0]

    def __enter__(self) -> "SimulationRunner":
        """Enter context manager."""
        return self

    def __exit__(self, exc_type: Any, exc_val: Any, exc_tb: Any) -> None:
        """Exit context manager, performing shutdown while preserving active exceptions."""
        self.close(in_flight_exc=exc_val)

    def __repr__(self) -> str:
        return (
            f"SimulationRunner(status={self._status!r}, "
            f"cycles_completed={self._simulation_cycles_completed}, "
            f"events_generated={self._events_generated}, "
            f"is_closed={self._is_closed})"
        )
