"""Canonical Version-1 Event Schema for AtmoSync Sensor Telemetry.

Defines the contract for individual sensor events generated by virtual containers.
Following Option A: One independent event per sensor reading.
"""

from dataclasses import dataclass
import math
from typing import Any, Dict, FrozenSet

SCHEMA_VERSION: int = 1
SUPPORTED_SENSOR_TYPES: FrozenSet[str] = frozenset({"temperature", "humidity", "vibration"})


@dataclass(frozen=True)
class SensorEvent:
    """Canonical representation of an individual IoT sensor reading event.

    Attributes:
        schema_version: Contract version integer (always 1 for this specification).
        event_id: Unique UUID string identifying this event.
        container_id: Configured shipping container identifier.
        sensor_type: Type of sensor ('temperature', 'humidity', or 'vibration').
        observed_at: Timezone-aware UTC ISO-8601 timestamp string (e.g. '2026-11-04T11:25:30.123Z').
        value: Finite numeric reading value.
        unit: Measurement unit string from sensor configuration.
    """

    schema_version: int
    event_id: str
    container_id: str
    sensor_type: str
    observed_at: str
    value: float
    unit: str

    def to_dict(self) -> Dict[str, Any]:
        """Convert the event to a canonical dictionary representation."""
        return {
            "schema_version": self.schema_version,
            "event_id": self.event_id,
            "container_id": self.container_id,
            "sensor_type": self.sensor_type,
            "observed_at": self.observed_at,
            "value": self.value,
            "unit": self.unit,
        }
